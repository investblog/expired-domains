import { defineConfig } from 'wxt';

// Manifest per SPEC section 8 and invariant I4: the permission set is frozen and checked by A2.
// No host_permissions, no optional_*, no web_accessible_resources, no tabs.
export default defineConfig({
  srcDir: 'src',
  outDir: 'dist',

  manifest: ({ browser }) => ({
    name: '__MSG_extName__',
    description: '__MSG_extDescription__',
    version: '0.1.1',
    default_locale: 'en',
    author: '301.st — Smart Traffic <support@301.st>',
    homepage_url: 'https://301.st',

    ...(browser === 'chrome' && { minimum_chrome_version: '116' }),

    // Toolbar button without a popup (SPEC Ф13а, as in geo-tier-builder): Chromium opens the side
    // panel via setPanelBehavior, Firefox opens the sidebar from browserAction.onClicked (both in
    // background). The side panel is the only extension page.
    ...(browser === 'firefox'
      ? {
          browser_action: { default_title: '__MSG_extName__' },
          // A bindable "toggle the sidebar" shortcut (the toolbar button opens it too).
          commands: { _execute_sidebar_action: { description: 'Toggle the Expired Domains sidebar' } },
        }
      : { action: { default_title: '__MSG_extName__' } }),

    permissions: browser === 'firefox' ? ['storage', 'unlimitedStorage'] : ['storage', 'unlimitedStorage', 'sidePanel'],

    icons: {
      16: 'icons/16.png',
      32: 'icons/32.png',
      48: 'icons/48.png',
      128: 'icons/128.png',
    },

    // side_panel (Chromium) and sidebar_action (Firefox) are generated by WXT from the `sidepanel`
    // entrypoint; its index.html carries the title and the sidebar icon.

    ...(browser === 'firefox' && {
      browser_specific_settings: {
        gecko: {
          id: 'expired-domains@301.st',
          // data_collection_permissions is understood since Firefox 140
          strict_min_version: '140.0',
          data_collection_permissions: {
            required: ['none'],
          },
        },
      },
    }),
  }),

  // Vite's modulepreload polyfill calls fetch() on the extension's own chunks; it is not needed
  // in extension pages and would be the only fetch in the bundle (I1, A1).
  vite: () => ({ build: { modulePreload: { polyfill: false } } }),

  zip: {
    excludeSources: ['temp/**', '.agents/**', 'AGENTS.md', 'CLAUDE.md'],
  },

  browser: 'chrome',
});
