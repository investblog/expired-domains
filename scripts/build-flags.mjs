#!/usr/bin/env node
// Country flags for the zone badges (SPEC Ф8), adapted from geo-tier-builder's build-flags.mjs:
// flag-icons (MIT) 4×3 flags, optimised with SVGO, one file per two-letter code in
// src/public/flags/ (the side panel loads only the flags of the zones it shows), plus the list of
// codes for src/sidepanel/zone.ts. Run after updating flag-icons: node scripts/build-flags.mjs
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { optimize } from 'svgo';

const FLAGS_DIR = resolve('node_modules/flag-icons/flags/4x3');
const OUT_DIR = resolve('src/public/flags');
const CODES_FILE = resolve('src/sidepanel/flag-codes.ts');
// flag-icons names a few territories by subdivision; their ccTLD is the key here.
const RENAMED = { 'sh-ac': 'ac' };

const sources = readdirSync(FLAGS_DIR)
  .map((f) => f.replace(/\.svg$/, ''))
  .filter((name) => /^[a-z]{2}$/.test(name) || name in RENAMED)
  .sort();

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const codes = [];
let bytes = 0;
for (const name of sources) {
  const code = RENAMED[name] ?? name;
  const raw = readFileSync(resolve(FLAGS_DIR, `${name}.svg`), 'utf8');
  const { data } = optimize(raw, { multipass: true, plugins: ['preset-default'] });
  writeFileSync(resolve(OUT_DIR, `${code}.svg`), data);
  codes.push(code);
  bytes += Buffer.byteLength(data);
}
copyFileSync(resolve('node_modules/flag-icons/LICENSE'), resolve(OUT_DIR, 'LICENSE.txt'));

codes.sort();
const version = JSON.parse(readFileSync(resolve('node_modules/flag-icons/package.json'), 'utf8')).version;
// Written in Biome's format, so a regeneration leaves no formatting diff.
writeFileSync(
  CODES_FILE,
  `// Generated by scripts/build-flags.mjs from flag-icons ${version} — do not edit.\n` +
    `// The two-letter codes that have a file in src/public/flags/.\n` +
    `export const FLAG_CODES: ReadonlySet<string> = new Set([\n${codes.map((c) => `  '${c}',\n`).join('')}]);\n`,
);
console.log(`${codes.length} flags, ${(bytes / 1024).toFixed(1)} KB → ${OUT_DIR}`);
